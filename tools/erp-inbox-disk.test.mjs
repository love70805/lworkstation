import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {Worker} from 'node:worker_threads';
import {createInboxDisk} from './erp-inbox-disk.mjs';
import {createInboxStorage,cloneInboxMetadata} from './erp-inbox-storage.mjs';
import {erpCatalogRequestProgress} from '../frontend/src/domain/erpCatalogRequest.js';

const directory=await fs.mkdtemp(path.join(os.tmpdir(),'erp-incremental-'));
try {
  const file=path.join(directory,'inbox.json');
  const envelope={type:'shopeers.erp.cost.batch',batch:{formatVersion:2,evidenceStatus:'complete',rows:[{platformSku:'SYNTHETIC',unitCost:0,evidence:'x'.repeat(2*1024*1024)}],warehouseEvidence:[{evidenceComplete:true}]}};
  const original=JSON.stringify([{kind:'batch',deliveryId:'one',status:'pending',envelope}]);
  await fs.writeFile(file,original);
  const store=createInboxStorage(file,{coldAcknowledged:true,checkpointOperations:4,checkpointBytes:16384});
  let initialWorker,initialRecords;
  const postMessage=Worker.prototype.postMessage;
  Worker.prototype.postMessage=function(...args){initialWorker=this;return postMessage.apply(this,args);};
  try {initialRecords=await store.read();} finally {Worker.prototype.postMessage=postMessage;}
  const pending=cloneInboxMetadata(initialRecords);
  assert.deepEqual(pending[0].envelope,envelope);
  pending[0].status='acknowledged';await store.write(pending);
  const cold=await store.read();
  assert.ok(cold[0].envelope.__inboxArchive);
  assert.ok(JSON.stringify(cold).length<1024,'acknowledged evidence leaves the resident HTTP snapshot');
  assert.deepEqual((await store.hydrate(cold[0])).envelope,envelope,'duplicate response can restore the exact cold evidence');
  await initialWorker.terminate();
  assert.strictEqual(await store.read(),cold,'unchanged disk retains the HTTP preview after worker failure');
  assert.deepEqual((await store.hydrate(cold[0])).envelope,envelope,'first hydration after worker failure restores exact evidence');
  assert.deepEqual((await store.hydrate(cold[0])).envelope,envelope,'subsequent duplicate hydration retains the replacement index');
  assert.deepEqual((await store.exportRecords())[0].envelope,envelope,'backup exports full cold evidence after worker failure');
  const backups=(await fs.readdir(directory)).filter(name=>name.includes('.legacy-'));
  assert.equal(backups.length,1);
  assert.equal(await fs.readFile(path.join(directory,backups[0]),'utf8'),original,'legacy source preserved byte-for-byte');
  const blob=(await fs.readdir(`${file}.evidence`))[0];
  const before=await fs.stat(path.join(`${file}.evidence`,blob));
  const written=[];
  for(let i=0;i<12;i++) {
    const rows=cloneInboxMetadata(await store.read());rows[0].note=`state-${i}`;
    await store.write(rows);
    written.push((await fs.stat(`${file}.journal`)).size);
  }
  assert.ok(written.every(bytes=>bytes<16384),'journal is bounded independently of historical evidence size');
  assert.ok((await fs.stat(file)).size<2048,'checkpoint contains metadata only');
  assert.equal((await fs.stat(path.join(`${file}.evidence`,blob))).mtimeMs,before.mtimeMs,'status changes never rewrite immutable evidence');
  const disk=createInboxDisk(file);await disk.load();
  const committed=await fs.readFile(`${file}.journal`);
  await fs.appendFile(`${file}.journal`,'{"data":"torn');
  assert.equal((await disk.load())[0].metadata.note,'state-11','torn unacknowledged tail is ignored');
  const entries=await disk.load();entries[0].metadata.note='after-torn';await disk.write(entries,disk.revision);
  assert.equal((await createInboxDisk(file).load())[0].metadata.note,'after-torn','next write removes only the torn tail');
  await fs.appendFile(`${file}.journal`,'{"data":"{}","checksum":"invalid"}\n');
  await assert.rejects(createInboxDisk(file).load(),{code:'ERP_INBOX_CORRUPT'});
  await fs.writeFile(`${file}.journal`,committed);
  await fs.rename(path.join(`${file}.evidence`,blob),path.join(`${file}.evidence`,blob+'.preserved'));
  await assert.rejects(store.hydrate(cold[0]),{code:'ERP_INBOX_CORRUPT'});
  await fs.rename(path.join(`${file}.evidence`,blob+'.preserved'),path.join(`${file}.evidence`,blob));
  await fs.writeFile(path.join(`${file}.evidence`,blob),'tampered');
  await assert.rejects(store.hydrate(cold[0]),{code:'ERP_INBOX_CORRUPT'});
  const brokenIndex=JSON.parse(await fs.readFile(file,'utf8'));brokenIndex.entries[0].metadata.status='edited';
  await fs.writeFile(file,JSON.stringify(brokenIndex));
  await assert.rejects(createInboxDisk(file).load(),{code:'ERP_INBOX_CORRUPT'});
  const catalog={type:'shopeers.erp.catalog.batch',catalog:{requestId:'R',workspaceId:'W',ledgerId:'L',ledgerPeriod:'2026-09',generatedAt:'2026-09-01T00:00:00Z',query:{platformSkcs:['A']},coverage:{images:{state:'complete'}},rows:[{image:'synthetic-'.repeat(100000)}]}};
  const catalogStore=createInboxStorage(path.join(directory,'catalog.json'),{coldAcknowledged:true});
  await catalogStore.write([{kind:'catalog-batch',status:'acknowledged',envelope:catalog}]);
  const archivedCatalog=(await catalogStore.read())[0];
  assert.ok(!archivedCatalog.envelope.catalog.rows);
  const request={requestId:'R',workspaceId:'W',ledgerId:'L',ledgerPeriod:'2026-09',platformSkcs:['A'],missingGroups:['images']};
  assert.deepEqual(erpCatalogRequestProgress(request,[archivedCatalog]),erpCatalogRequestProgress(request,[{envelope:catalog}]),'cold catalog preserves exact coverage progress');
  assert.deepEqual((await catalogStore.hydrate(archivedCatalog)).envelope,catalog);
  const clearFile=path.join(directory,'clear.json'),clearStore=createInboxStorage(clearFile,{coldAcknowledged:true});
  await fs.writeFile(clearFile,original);
  const old=cloneInboxMetadata(await clearStore.read());old[0].status='acknowledged';await clearStore.write(old);
  const oldJournal=await fs.readFile(clearFile+'.journal');
  assert.ok((await fs.readdir(directory)).some(name=>name.startsWith('clear.json.legacy-')));
  await fs.writeFile(path.join(directory,'manual-export.json'),original);
  const interruptedBackup=clearFile+'.legacy-'+('a'.repeat(64))+'.json.00000000-0000-4000-8000-000000000000.tmp';
  await fs.writeFile(interruptedBackup,original);
  for(const blob of await fs.readdir(clearFile+'.evidence'))await fs.writeFile(path.join(clearFile+'.evidence',blob),'damaged evidence');
  await clearStore.reset([]);
  assert.deepEqual(await clearStore.read(),[]);
  await assert.rejects(fs.access(clearFile+'.evidence'),{code:'ENOENT'});
  assert.equal((await fs.readdir(directory)).some(name=>name.startsWith('clear.json.legacy-')),false);
  assert.equal(await fs.readFile(path.join(directory,'manual-export.json'),'utf8'),original);
  // Simulate interruption after the new checkpoint but before log rotation.
  await fs.writeFile(clearFile+'.journal',oldJournal);
  assert.deepEqual(await createInboxDisk(clearFile).load(),[]);
  await clearStore.read();
  await clearStore.reset([]);
  assert.equal(await fs.readFile(clearFile+'.journal','utf8'),'');
  await clearStore.write([{kind:'request',requestId:'fresh',status:'registered'}]);
  assert.equal((await clearStore.read())[0].requestId,'fresh');
  console.log('Incremental inbox: legacy preservation, exact cold hydration/backup after worker failure, bounded journal/checkpoint, unchanged evidence, torn tail and checksum rejection passed');
} finally {await fs.rm(directory,{recursive:true,force:true});}
